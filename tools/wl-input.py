#!/usr/bin/env python3
"""A persistent virtual pointer and keyboard for a wlroots compositor.

Used by tools/smoke-run.sh to drive the app on headless sway. One-shot tools
such as wtype create their input device, send events and exit; a client that
has not yet bound the seat's keyboard or pointer never sees those events.
This helper keeps both devices alive for the whole session, so the seat's
capabilities are stable before the app starts.

Reads one command per line from stdin:

    move X Y          pointer to layout position (logical pixels)
    press | release   left mouse button
    click X Y         move, press, release
    type TEXT...      type text (US layout: letters, digits, common punctuation)
    key NAME          Return, Escape, Tab, BackSpace, Left, Right, Up, Down
    ctrl KEY          Control + a letter, digit or punctuation key
    swipe DX          two fingers moved DX pixels sideways on a trackpad
    sleep SECONDS

Usage: wl-input.py --protocols DIR --extent WIDTH HEIGHT
where DIR holds bindings generated by pywayland's scanner (see smoke-run.sh)
and WIDTH × HEIGHT is the size of the whole output layout.
"""

import argparse
import os
import subprocess
import sys
import time

BTN_LEFT = 0x110
AXIS_HORIZONTAL = 1  # wl_pointer.axis
AXIS_SOURCE_FINGER = 1  # wl_pointer.axis_source
SHIFT, CONTROL = 42, 29  # evdev key codes
SHIFT_MASK, CONTROL_MASK = 1, 4

LETTERS = dict(zip(
    "abcdefghijklmnopqrstuvwxyz",
    [30, 48, 46, 32, 18, 33, 34, 35, 23, 36, 37, 38, 50, 49, 24, 25, 16, 19, 31,
     20, 22, 47, 17, 45, 21, 44],
))
PLAIN = {
    **LETTERS,
    **{str(d): c for d, c in zip("1234567890", range(2, 12))},
    " ": 57, "-": 12, "=": 13, ",": 51, ".": 52, "/": 53, ";": 39, "'": 40,
}
SHIFTED = {
    **{k.upper(): v for k, v in LETTERS.items()},
    "!": 2, "?": 53, ":": 39, "_": 12, "+": 13, '"': 40, "(": 10, ")": 11,
}
NAMED = {
    "Return": 28, "Escape": 1, "Tab": 15, "BackSpace": 14,
    "Left": 105, "Right": 106, "Up": 103, "Down": 108,
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--protocols", required=True)
    parser.add_argument("--extent", nargs=2, type=int, required=True)
    args = parser.parse_args()
    sys.path.insert(0, args.protocols)

    from pywayland.client import Display
    from protocols.wayland import WlSeat
    from protocols.virtual_keyboard_unstable_v1 import ZwpVirtualKeyboardManagerV1
    from protocols.wlr_virtual_pointer_unstable_v1 import ZwlrVirtualPointerManagerV1

    display = Display()
    display.connect()
    found = {}

    def on_global(registry, name, interface, version):
        if interface == "wl_seat" and "seat" not in found:
            found["seat"] = registry.bind(name, WlSeat, min(version, 5))
        elif interface == "zwlr_virtual_pointer_manager_v1":
            found["pointer"] = registry.bind(name, ZwlrVirtualPointerManagerV1, 1)
        elif interface == "zwp_virtual_keyboard_manager_v1":
            found["keyboard"] = registry.bind(name, ZwpVirtualKeyboardManagerV1, 1)

    registry = display.get_registry()
    registry.dispatcher["global"] = on_global
    display.roundtrip()
    missing = {"seat", "pointer", "keyboard"} - found.keys()
    if missing:
        sys.exit(f"compositor lacks: {', '.join(sorted(missing))}")

    pointer = found["pointer"].create_virtual_pointer(found["seat"])
    keyboard = found["keyboard"].create_virtual_keyboard(found["seat"])

    keymap = subprocess.run(
        ["xkbcli", "compile-keymap", "--layout", "us"],
        check=True, capture_output=True,
    ).stdout + b"\0"
    fd = os.memfd_create("keymap")
    os.write(fd, keymap)
    keyboard.keymap(1, fd, len(keymap))  # 1 = XKB v1 text format
    display.roundtrip()
    os.close(fd)

    width, height = args.extent

    def now():
        return int(time.monotonic() * 1000) & 0x7FFFFFFF

    def move(x, y):
        pointer.motion_absolute(now(), int(x), int(y), width, height)
        pointer.frame()

    def button(down):
        pointer.button(now(), BTN_LEFT, 1 if down else 0)
        pointer.frame()

    def step():
        # Deliver what has been sent and leave a gap, as between real key
        # events. A whole chord sent in one burst can reach the client before
        # it has processed the modifier change that precedes the key.
        display.roundtrip()
        time.sleep(0.015)

    def tap(code, mask=0, modifier=None):
        if modifier is not None:
            keyboard.key(now(), modifier, 1)
            keyboard.modifiers(mask, 0, 0, 0)
            step()
        keyboard.key(now(), code, 1)
        step()
        keyboard.key(now(), code, 0)
        step()
        if modifier is not None:
            keyboard.key(now(), modifier, 0)
            keyboard.modifiers(0, 0, 0, 0)
            step()

    print("ready", flush=True)
    for line in sys.stdin:
        command, _, rest = line.rstrip("\n").partition(" ")
        if command == "move":
            x, y = rest.split()
            move(x, y)
        elif command == "press":
            button(True)
        elif command == "release":
            button(False)
        elif command == "click":
            x, y = rest.split()
            move(x, y)
            display.roundtrip()
            time.sleep(0.05)
            button(True)
            display.roundtrip()
            time.sleep(0.05)
            button(False)
        elif command == "type":
            for char in rest:
                if char in PLAIN:
                    tap(PLAIN[char])
                elif char in SHIFTED:
                    tap(SHIFTED[char], SHIFT_MASK, SHIFT)
                else:
                    sys.exit(f"cannot type {char!r}")
        elif command == "key":
            tap(NAMED[rest])
        elif command == "ctrl":
            tap(PLAIN[rest], CONTROL_MASK, CONTROL)
        elif command == "swipe":
            # Two fingers moved sideways on a trackpad: a run of small
            # scroll steps said to come from a finger, then their end. A
            # negative distance is a swipe to the left.
            total, steps = float(rest), 14
            for _ in range(steps):
                pointer.axis_source(AXIS_SOURCE_FINGER)
                # The fingers move the content: to the left scrolls right.
                pointer.axis(now(), AXIS_HORIZONTAL, -total / steps)
                pointer.frame()
                display.roundtrip()
                time.sleep(0.016)
            pointer.axis_source(AXIS_SOURCE_FINGER)
            pointer.axis_stop(now(), AXIS_HORIZONTAL)
            pointer.frame()
        elif command == "sleep":
            time.sleep(float(rest))
        elif command:
            sys.exit(f"unknown command {command!r}")
        display.roundtrip()


if __name__ == "__main__":
    main()
